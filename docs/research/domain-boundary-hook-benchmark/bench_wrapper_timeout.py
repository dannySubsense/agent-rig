#!/usr/bin/env python3
"""Wall-clock benchmark for the domain-boundary-provenance PreToolUse wrapper's outer
`timeout` bound (.claude/hooks/domain-boundary-provenance.sh).

Measures the FULL wrapper path (stdin capture -> mode resolve -> probe under timeout ->
output validation), not the probe alone, because the wrapper's `timeout N` bounds the probe
subprocess only but the value must be defensible against the probe's own worst case.

Worst-case input: a Write tool_input whose `content` is the largest .py file in this repo.
`get_scan_surface` (probe L211) reads the payload, never the on-disk file, so payload size
is the scaling axis and the largest .py is the realistic ceiling for an agent-authored Write.

Regenerate: python3 docs/research/domain-boundary-hook-benchmark/bench_wrapper_timeout.py
Writes: results-wrapper-timeout-<run-timestamp>.md alongside the committed
results-wrapper-timeout.md, WITHOUT touching the committed file, so a later re-run's
recommendation can never silently overwrite the measurement the shipped timeout was cited
against. Pass --overwrite-committed to replace results-wrapper-timeout.md itself; that is a
deliberate, separate act, not the default of running the script.

The committed 3s timeout is a ceiling based on the original committed measurement run. A
later re-run producing a lower recommended value does NOT automatically lower the shipped
timeout -- changing the wrapper's timeout requires a deliberate, separate decision to
re-cite (updating the wrapper comment and results file together, on purpose).
"""
import argparse, json, os, subprocess, sys, time, statistics, platform
from datetime import datetime, timezone

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
WRAPPER = os.path.join(REPO, ".claude", "hooks", "domain-boundary-provenance.sh")
TRACK = os.path.join(REPO, "docs", "tooling", "domain-boundary-provenance-track-record.jsonl")
N = 50
SESSION_ID = "bench-wrapper-timeout"
SKIP_DIRS = {".git", "__pycache__", ".venv", "venv", "node_modules", ".gate-snapshots", "archive"}


def largest_py():
    best = (0, None)
    for root, dirs, files in os.walk(REPO):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            if f.endswith(".py"):
                p = os.path.join(root, f)
                s = os.path.getsize(p)
                if s > best[0]:
                    best = (s, p)
    return best


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--overwrite-committed", action="store_true",
                         help="Replace the committed results-wrapper-timeout.md in place "
                              "instead of writing a new timestamped file. This is a "
                              "deliberate re-citation act, not the default.")
    args = parser.parse_args()

    size, path = largest_py()
    content = open(path, encoding="utf-8").read()
    payload = json.dumps({
        "session_id": SESSION_ID, "tool_name": "Write", "cwd": REPO,
        "tool_input": {"file_path": path, "content": content},
    }).encode()

    pre_lines = sum(1 for _ in open(TRACK)) if os.path.exists(TRACK) else 0
    times = []
    for _ in range(N):
        t0 = time.perf_counter()
        subprocess.run([WRAPPER], input=payload, stdout=subprocess.PIPE,
                       stderr=subprocess.PIPE, check=False)
        times.append(time.perf_counter() - t0)

    # Remove this benchmark's own track-record lines so the run leaves no residue.
    if os.path.exists(TRACK):
        kept = [l for l in open(TRACK) if SESSION_ID not in l]
        open(TRACK, "w").writelines(kept)
        post = len(kept)
    else:
        post = 0

    ts = sorted(times)
    def q(p):  # nearest-rank percentile
        return ts[min(len(ts) - 1, max(0, int(-(-p * len(ts) // 100)) - 1))]
    p50, p95, p99, mx = q(50), q(95), q(99), ts[-1]
    stdev = statistics.stdev(ts)
    margin = 20.0
    rec = p99 * margin

    out = f"""# Wrapper Timeout Benchmark — Committed Results

**Generated by**: `docs/research/domain-boundary-hook-benchmark/bench_wrapper_timeout.py`
**Regenerate**: `python3 docs/research/domain-boundary-hook-benchmark/bench_wrapper_timeout.py`
**Run at**: {datetime.now(timezone.utc).isoformat()}
**Python**: {platform.python_version()} — **Platform**: {platform.platform()}

Machine-generated. Do not hand-edit — rerun the script.

## 1. What is measured

Wall-clock time of a full `.claude/hooks/domain-boundary-provenance.sh` invocation
(stdin capture, mode resolution, probe subprocess under `timeout`, output validation),
driven by a `Write` tool_input carrying the largest `.py` file in this repo as `content`.
N = {N} sequential runs, single machine, no warm-up discarded.

**Scope limit, stated plainly**: this is one machine, one repo, one cold-ish filesystem
state. It is not a cross-host or cross-load distribution. It bounds the value; it does not
prove the value holds on unmeasured hardware.

## 2. Worst-case input

| Field | Value |
|---|---|
| File | `{os.path.relpath(path, REPO)}` |
| Size | {size:,} bytes |
| Tool | `Write` (scan surface = `tool_input.content`, probe L211) |

## 3. Latency distribution (seconds)

| Stat | Value |
|---|---|
| min | {ts[0]:.4f} |
| p50 | {p50:.4f} |
| p95 | {p95:.4f} |
| p99 | {p99:.4f} |
| max | {mx:.4f} |
| mean | {statistics.mean(ts):.4f} |
| stdev | {stdev:.4f} |

Raw per-run times (seconds), run order:

```
{json.dumps([round(t, 4) for t in times])}
```

## 4. Margin and resulting timeout

Measured p99 = **{p99:.4f}s**. Margin multiplier **{margin:g}x** -> {rec:.4f}s.

Margin reasoning: the failure mode of a too-small timeout is a false `probe_error` on a
legitimate edit (the hook silently stops doing its job); the failure mode of a too-large
timeout is a bounded stall the agent absorbs once. Those costs are asymmetric, so the
margin is deliberately generous rather than tight.

The measured cost is dominated by fixed overhead (two Python interpreter starts plus an AST
parse of a 66 KB payload), not by anything that scales with repo or corpus size, and the
run-to-run spread is small (stdev {stdev:.4f}s). The variance this bound must actually absorb
is therefore HOST variance, not input variance: interpreter startup and cold page-cache reads
on a contended VM can degrade by an order of magnitude. {margin:g}x on a p99 of {p99:.4f}s
covers a ~{margin:g}x-slower host with room, and the resulting stall is still one an agent
absorbs once. A tighter multiplier (e.g. 5x -> 0.5s, rounding to the 1s granularity `timeout`
accepts) would sit inside plausible host-slowdown range and risk false `probe_error`s on
legitimate edits.

**Recommended timeout: {max(1, int(-(-rec // 1)))}s** (ceiling of p99 x {margin:g}).

**On re-runs**: the shipped wrapper timeout (3s) is a ceiling based on the ORIGINAL committed
measurement run, not on whichever run happened most recently. If this run's recommended value
above is lower than 3s, that does NOT automatically lower the shipped timeout -- reducing it
requires a deliberate, separate decision to re-cite (updating both the wrapper comment in
`.claude/hooks/domain-boundary-provenance.sh` and this results file together, on purpose, not
as a side effect of re-running the script).

## 5. Track-record hygiene

The benchmark's own runs append `probe_error`/allow lines to
`docs/tooling/domain-boundary-provenance-track-record.jsonl`. The script deletes every line
carrying `session_id == "{SESSION_ID}"` after the run. Line count before: {pre_lines}; after: {post}.
"""
    here = os.path.dirname(__file__)
    committed = os.path.join(here, "results-wrapper-timeout.md")
    if args.overwrite_committed:
        dest = committed
    else:
        stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        dest = os.path.join(here, f"results-wrapper-timeout-{stamp}.md")
        print(f"NOTE: committed results-wrapper-timeout.md left untouched. "
              f"Writing this run's output to {dest} instead. "
              f"Pass --overwrite-committed to replace the committed file deliberately.")
    open(dest, "w").write(out)
    print(out)


if __name__ == "__main__":
    main()
