def recall_check() -> list[dict]:
    results = []

    # I1 -- live file at HEAD
    r1 = {"id": "I1", "constant": "_HEAD_BYTES = 65_536",
          "location": str(INCIDENT_1), "status": None, "flagged_by": [], "detail": ""}
    if not INCIDENT_1.exists():
        r1["status"] = "MISSING -- file not found on this machine, recall NOT measured"
    else:
        src = INCIDENT_1.read_text(encoding="utf-8", errors="replace")
        cands = scan_source("gap-lens-dilution-filter", INCIDENT_2_PATH and str(
            INCIDENT_1.relative_to(INCIDENT_2_REPO)), src)
        hits = [c for c in cands if c.target_name == "_HEAD_BYTES"]
        r1["status"] = "PRESENT"
        for rule in RULES:
            if any(rule in c.rules() and c.net_flagged() for c in hits):
                r1["flagged_by"].append(rule)
        r1["detail"] = "; ".join(
            f"line {c.line} ctx={c.context} value={c.value_repr} upper={c.is_upper} "
            f"net_flagged={c.net_flagged()}" for c in hits) or "constant not found in file"
    results.append(r1)

    # I2 -- DELETED at HEAD, recovered from git history
    r2 = {"id": "I2", "constant": "filing_text_max_bytes: int = 512_000",
          "location": f"{INCIDENT_2_REPO}/{INCIDENT_2_PATH} @ {INCIDENT_2_REV} (deleted at HEAD)",
          "status": None, "flagged_by": [], "detail": ""}
    try:
        src = subprocess.run(
            ["git", "-C", str(INCIDENT_2_REPO), "show", f"{INCIDENT_2_REV}:{INCIDENT_2_PATH}"],
            capture_output=True, text=True, check=True).stdout
        r2["status"] = f"RECOVERED from git rev {INCIDENT_2_REV}"
        cands = scan_source("gap-lens-dilution-filter", INCIDENT_2_PATH, src)
        hits = [c for c in cands if c.target_name == "filing_text_max_bytes"]
        for rule in RULES:
            if any(rule in c.rules() and c.net_flagged() for c in hits):
                r2["flagged_by"].append(rule)
        r2["detail"] = "; ".join(
            f"line {c.line} ctx={c.context} value={c.value_repr} upper={c.is_upper} "
            f"net_flagged={c.net_flagged()}" for c in hits) or "constant not found at that rev"
    except (subprocess.CalledProcessError, FileNotFoundError) as e:
        r2["status"] = f"UNAVAILABLE -- could not recover from git ({e}); recall NOT measured"
    results.append(r2)
    return results


