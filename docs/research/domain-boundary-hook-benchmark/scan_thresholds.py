    A("not a tuning result -- it is structural: a `range()` positional argument is a call argument,")
    A("which is not a comparison operand, a slice bound, or a module/class-level assignment target,")
    A("so it is never generated as a candidate by ANY of rules (a)-(d) in the first place. The")
    A("exclusion is inert under this design and removing it would change no count above. It is")
    A("reported here rather than quietly dropped.")
    A("")
    A("Candidates by syntactic context (rule-independent raw counts):")
    A("")
    A("| Context | Count |")
    A("|---|---|")
    for ctx, n in sorted(Counter(c.context for c in all_cands).items()):
        A(f"| `{ctx}` | {n} |")
    A("")
    A("## 4. Recall on the real historical incidents (the disqualifying test)")
    A("")
    A("Both incidents this hook was built from (DDR-0014) are named-constant assignments.")
    A("A rule that cannot flag these is disqualified regardless of its false-positive rate.")
    A("")
    A("| Incident | Constant | Source status | Flagged by |")
    A("|---|---|---|---|")
    for r in recalls:
        fb = ", ".join(r["flagged_by"]) if r["flagged_by"] else "**NONE**"
        A(f"| {r['id']} | `{r['constant']}` | {r['status']} | {fb} |")
    A("")
    for r in recalls:
        A(f"- **{r['id']}** `{r['location']}` — {r['detail']}")
    A("")
    A("| Rule | I1 `_HEAD_BYTES` | I2 `filing_text_max_bytes` | Recall |")
    A("|---|---|---|---|")
    for rule in RULES:
        h = ["PASS" if rule in r["flagged_by"] else "MISS" for r in recalls]
        A(f"| {rule} | {h[0]} | {h[1]} | {h.count('PASS')}/2 |")
    A("")
    A("## 5. Citation-proximity window — measured distribution")
    A("")
    A("Measured over the assignment-context candidates specifically (rule c, and rule d as a")
    A("subset), net of exclusions. Distance 1 = comment on the line immediately above the")
    A("assignment; blank lines are scanned through; a non-comment code line terminates the")
    A("scan (so distances are real comment-to-constant gaps, not any nearby comment).")
    A("Search capped at 12 lines.")
    A("")
    for label, p in (("Rule (c) — all name-bound assignments", prox_c),
                     ("Rule (d) — UPPER_CASE targets only", prox_d)):
        A(f"### {label}")
        A("")
        A(f"- Assignment candidates (net of exclusions): **{p['assignment_candidates']}**")
        A(f"- With a preceding comment within 12 lines: **{p['with_preceding_comment']}** "
          f"({p['with_preceding_comment_pct']}%)")
        A("")
        A("| Distance (lines) | Count |")
        A("|---|---|")
        for d, n in p["distance_histogram"].items():
            A(f"| {d} | {n} |")
        A("")
        A("Cumulative share of commented assignments captured by a window of size W:")
        A("")
        A("| W | Coverage of commented assignments |")
        A("|---|---|")
        for w, pct in p["cumulative_coverage_pct"].items():
            A(f"| {w} | {pct}% |")
        A("")
    A("## 6. What this benchmark does NOT decide")
    A("")
    A("Rule selection is an architecture decision, not a benchmark verdict. This script reports")
    A("recall on the two known true positives and the false-positive volume profile of each rule.")
    A("It deliberately does not pick a winner: the precision of the flagged volume is unlabeled")
    A("(no hand-labeled sample was drawn), so 'net flagged' is volume, not false positives.")
    A("The `{0,1,-1,2}` exclusion set remains unvalidated — this run measures its SHARE, which is")
    A("its leverage, not its correctness. Both remain open for a human decision.")
    A("")
    (HERE / "results.md").write_text("\n".join(L) + "\n")

    print(f"files scanned: {total_files}; candidates: {len(all_cands)}")
    for r in RULES:
        print(f"  rule {r}: total={stats[r]['total_candidates']:6d} net={stats[r]['net_flagged']:6d} "
              f"excl_value_share={stats[r]['excl_value_share_pct']}%")
    for r in recalls:
        print(f"  recall {r['id']}: {r['status']} flagged_by={r['flagged_by'] or 'NONE'}")
    print(f"wrote {HERE/'results.md'} and {HERE/'candidates.jsonl'}")
    return 0


