SELF_DIR = HERE


def iter_py_files(root: Path):
    for dirpath, dirnames, filenames in os.walk(root):
        if Path(dirpath) == SELF_DIR or SELF_DIR in Path(dirpath).parents:
            dirnames[:] = []
            continue
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for fn in sorted(filenames):
            if fn.endswith(".py"):
                yield Path(dirpath) / fn


def is_test_path(relpath: str) -> bool:
    parts = Path(relpath).parts
    if any(p.lower() in TEST_PATH_COMPONENTS for p in parts[:-1]):
        return True
    stem = Path(relpath).stem.lower()
    return stem.startswith("test_") or stem.endswith("_test") or stem == "conftest"


def scan_source(repo: str, relpath: str, source: str) -> list[Candidate]:
    """Whole-file entrypoint. Now routed through the §2.1 fragment-robust chain so the
    corpus numbers on record are regenerated by the SAME code path the fragment matrix
    exercises (a whole file parses under strategy 1, so counts must not move)."""
    cands, _strategy = scan_source_fragment(repo, relpath, source)
    return cands


def scan_file(repo: str, root: Path, path: Path) -> list[Candidate]:
    try:
        source = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return []
    return scan_source(repo, str(path.relative_to(root)), source)


