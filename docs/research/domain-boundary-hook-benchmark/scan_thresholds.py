def main() -> int:
    all_cands: list[Candidate] = []
    corpus_report = []
    for repo, root in CORPUS_ROOTS:
        if not root.exists():
            corpus_report.append((repo, str(root), "MISSING", 0))
            continue
        files = list(iter_py_files(root))
        for p in files:
            all_cands.extend(scan_file(repo, root, p))
        corpus_report.append((repo, str(root), "present", len(files)))

    total_files = sum(n for *_, n in corpus_report)

    # per-rule tallies
    stats = {}
    for rule in RULES:
        sel = [c for c in all_cands if rule in c.rules()]
        stats[rule] = {
            "total_candidates": len(sel),
            "excl_value_set": sum(1 for c in sel if c.in_excluded_values),
            "excl_range": sum(1 for c in sel if c.in_range_call),
            "excl_test_path": sum(1 for c in sel if c.in_test_path),
            "net_flagged": sum(1 for c in sel if c.net_flagged()),
            "by_context": dict(Counter(c.context for c in sel)),
            "excl_value_share_pct": round(
                100.0 * sum(1 for c in sel if c.in_excluded_values) / len(sel), 1) if sel else 0.0,
        }

    recalls = recall_check()

    # citation-proximity distribution over rule (c)/(d) assignment candidates
    assign_cands = [c for c in all_cands if c.context.startswith("assign") and c.net_flagged()]
    def prox(cands):
        commented = [c for c in cands if c.comment_distance is not None]
        return {
            "assignment_candidates": len(cands),
            "with_preceding_comment": len(commented),
            "with_preceding_comment_pct": round(100.0 * len(commented) / len(cands), 1) if cands else 0.0,
            "distance_histogram": dict(sorted(Counter(c.comment_distance for c in commented).items())),
            "cumulative_coverage_pct": {
                w: round(100.0 * sum(1 for c in commented if c.comment_distance <= w) / len(commented), 1)
                for w in range(1, 13)
            } if commented else {},
        }
    prox_c = prox(assign_cands)
    prox_d = prox([c for c in assign_cands if c.is_upper])

    # ---- write JSONL ----
    with open(HERE / "candidates.jsonl", "w") as fh:
        for c in sorted(all_cands, key=lambda x: (x.repo, x.path, x.line, x.context)):
            d = asdict(c)
            d["rules"] = sorted(c.rules())
            d["net_flagged"] = c.net_flagged()
            fh.write(json.dumps(d) + "\n")

    # ---- write results.md ----
    L = []
    A = L.append
    A("# Detection-Rule Benchmark — Committed Results")
    A("")
    A("**Generated by**: `docs/research/domain-boundary-hook-benchmark/scan_thresholds.py`  ")
    A("**Regenerate**: `python3 docs/research/domain-boundary-hook-benchmark/scan_thresholds.py`  ")
    A(f"**Python**: {sys.version.split()[0]}  ")
    A("**Raw rows**: `candidates.jsonl` (one line per candidate, with rule membership and exclusion flags)")
    A("")
    A("This file is machine-generated. Do not hand-edit — rerun the script. Every number a")
    A("spec cites must point at this path, not restate the value in prose.")
    A("")
    A("## 1. Corpus")
    A("")
    A("Defined in `CORPUS_ROOTS` in the script: this repo (`agent-rig`) plus the repos listed in")
    A("`docs/specs/agent-rig-ddrs/HOOK-DEPLOYMENT-ROSTER.md` plus `market_data`, per")
    A("`02-ARCHITECTURE.md` §2 disposition step 1. Walked recursively for `.py`; vendored and")
    A(f"generated trees skipped ({', '.join(sorted(SKIP_DIRS))}). This benchmark's own directory")
    A("is also excluded, so the script does not count its own dataclass defaults as candidates.")
    A("")
    A("| Repo | Path | Status | `.py` files scanned |")
    A("|---|---|---|---|")
    for repo, path, status, n in corpus_report:
        A(f"| `{repo}` | `{path}` | {status} | {n} |")
    A(f"| **TOTAL** | | | **{total_files}** |")
    A("")
    missing = [r for r, _, s, _ in corpus_report if s == "MISSING"]
    A(f"Missing corpus roots (reported, not guessed): {missing if missing else 'none'}")
    A("")
