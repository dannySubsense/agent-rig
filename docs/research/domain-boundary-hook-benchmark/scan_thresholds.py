@dataclass
class Candidate:
    repo: str
    path: str
    line: int
    value: object
    value_repr: str
    context: str          # "comparison" | "slice_trunc" | "assign_module" | "assign_class"
    target_name: str | None = None
    is_upper: bool = False
    in_range_call: bool = False
    in_test_path: bool = False
    in_excluded_values: bool = False
    comment_distance: int | None = None   # lines from nearest preceding comment block
    comment_text: str | None = None

    def rules(self) -> set[str]:
        """Which candidate rules (a)-(d) generate this candidate at all (pre-exclusion)."""
        if self.context == "comparison":
            return {"a", "b", "c", "d"}
        if self.context == "slice_trunc":
            return {"b", "c", "d"}
        # assignment contexts
        return {"c", "d"} if self.is_upper else {"c"}

    def net_flagged(self) -> bool:
        """Survives ALL existing exclusions from §2."""
        return not (self.in_range_call or self.in_test_path or self.in_excluded_values)


def is_upper_name(name: str) -> bool:
    """UPPER_CASE / UPPER_SNAKE_CASE, leading underscores allowed (_HEAD_BYTES)."""
    core = name.lstrip("_")
    return bool(core) and core.upper() == core and any(ch.isalpha() for ch in core)


def literal_value(node: ast.AST):
    """Numeric/bool literal, including unary minus. Returns (value, ok). Excludes str/None."""
    if isinstance(node, ast.Constant) and isinstance(node.value, (int, float, bool)):
        return node.value, True
    if (isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.USub, ast.UAdd))
            and isinstance(node.operand, ast.Constant)
            and isinstance(node.operand.value, (int, float))):
        v = node.operand.value
        return (-v if isinstance(node.op, ast.USub) else v), True
    return None, False


TRUNCATION_METHODS = {"ljust", "rjust", "zfill", "truncate", "read", "head"}


class Scanner(ast.NodeVisitor):
    """Collects candidates. Records CONTEXT and EXCLUSION FLAGS; rule membership is
    derived later so all four rules see identical raw evidence."""

    def __init__(self, repo: str, relpath: str, source_lines: list[str], in_test_path: bool):
        self.repo = repo
        self.relpath = relpath
        self.lines = source_lines
        self.in_test_path = in_test_path
        self.out: list[Candidate] = []
        self._range_lines: set[tuple[int, int]] = set()  # (lineno, col) of range() arg literals

    # -- exclusion pre-pass: mark literals that are range() positional args 1-3 --
    def mark_range_args(self, tree: ast.AST):
        for node in ast.walk(tree):
            if (isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
                    and node.func.id == "range"):
                for arg in node.args[:3]:
                    for sub in ast.walk(arg):
                        if isinstance(sub, ast.Constant):
                            self._range_lines.add((sub.lineno, sub.col_offset))

    def _is_range(self, node) -> bool:
        target = node.operand if isinstance(node, ast.UnaryOp) else node
        return (getattr(target, "lineno", None), getattr(target, "col_offset", None)) in self._range_lines

    def _add(self, node, context, target_name=None):
        val, ok = literal_value(node)
        if not ok:
            return
        # bools only count in the assignment contexts (a bool comparison operand is
        # `x == True`, idiomatic-rare and not threshold-shaped)
        if isinstance(val, bool) and not context.startswith("assign"):
            return
        c = Candidate(
            repo=self.repo, path=self.relpath, line=node.lineno,
            value=val, value_repr=repr(val), context=context,
            target_name=target_name,
            is_upper=is_upper_name(target_name) if target_name else False,
            in_range_call=self._is_range(node),
            in_test_path=self.in_test_path,
            in_excluded_values=(not isinstance(val, bool)) and val in EXCLUDED_VALUES,
        )
        if context.startswith("assign"):
            d, t = self._preceding_comment(node.lineno)
            c.comment_distance, c.comment_text = d, t
        self.out.append(c)

    def _preceding_comment(self, lineno: int):
        """Distance in lines from the assignment to the LAST line of the nearest preceding
        comment block, scanning upward past blank lines. Distance 1 == comment on the
        immediately preceding line. Returns (None, None) if no comment within 12 lines."""
        i = lineno - 2  # 0-based index of the line above
        dist = 1
        while i >= 0 and dist <= 12:
            stripped = self.lines[i].strip()
            if stripped.startswith("#"):
                return dist, stripped[:120]
            if stripped == "":
                i -= 1
                dist += 1
                continue
            return None, None  # hit real code before a comment
        return None, None

    # -- contexts --
    def visit_Compare(self, node: ast.Compare):
        if any(isinstance(op, (ast.Lt, ast.LtE, ast.Gt, ast.GtE, ast.Eq, ast.NotEq))
               for op in node.ops):
            for operand in [node.left, *node.comparators]:
                self._add(operand, "comparison")
        self.generic_visit(node)

    def visit_Subscript(self, node: ast.Subscript):
        if isinstance(node.slice, ast.Slice):
            for part in (node.slice.lower, node.slice.upper, node.slice.step):
                if part is not None:
                    self._add(part, "slice_trunc")
        self.generic_visit(node)

    def visit_Call(self, node: ast.Call):
        if isinstance(node.func, ast.Attribute) and node.func.attr in TRUNCATION_METHODS:
            for arg in node.args:
                self._add(arg, "slice_trunc")
        self.generic_visit(node)

    def scan_assignments(self, tree: ast.Module):
        """Module-level and class-body name-bound literal assignments. Pure shape:
        the target must be a bare Name and the statement must sit directly in a Module
        body or a ClassDef body (NOT inside a function). No word list, no vocabulary."""
        def handle(body, context):
            for stmt in body:
                if isinstance(stmt, ast.Assign):
                    for tgt in stmt.targets:
                        if isinstance(tgt, ast.Name):
                            self._add(stmt.value, context, target_name=tgt.id)
                elif isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                    if stmt.value is not None:
                        self._add(stmt.value, context, target_name=stmt.target.id)
                elif isinstance(stmt, ast.ClassDef):
                    handle(stmt.body, "assign_class")
        handle(tree.body, "assign_module")


# ---------------------------------------------------------------------------
# FRAGMENT-ROBUST PARSING (02-ARCHITECTURE.md §2.1, G-1 fix)
# ---------------------------------------------------------------------------
# The hook's real scan surface is tool_input.new_string / tool_input.content -- a
# FRAGMENT, not a whole file. An indented class-body fragment (I2's exact shape)
# raises IndentationError under a bare ast.parse and yields ZERO candidates.
# §2.1 specifies a three-strategy chain. Implemented here verbatim.

# §2.1 strategy 3: per-line regex, context 3 (assignment) ONLY. Contexts 1-2 get
# no textual fallback by design (false-positive risk against strings/type hints).
FRAGMENT_ASSIGN_RE = re.compile(
    r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*(?::\s*[\w.\[\], ]+)?\s*=\s*"
    r"(-?\d[\d_]*|True|False)\s*(?:#.*)?$"
)

PARSE_DIRECT = "direct_parse"
PARSE_DEDENT = "dedent_retry"
PARSE_REGEX = "regex_fallback"
PARSE_NONE = "none"


def parse_fragment(source: str):
    """Returns (tree_or_None, strategy_name). §2.1:
      1. ast.parse(source)
      2. on IndentationError ONLY: ast.parse(textwrap.dedent(source))
      3. on any remaining SyntaxError: caller falls back to regex (context 3 only)."""
    try:
        return ast.parse(source), PARSE_DIRECT
    except IndentationError:
        try:
            return ast.parse(textwrap.dedent(source)), PARSE_DEDENT
        except SyntaxError:
            return None, PARSE_REGEX
    except SyntaxError:
        return None, PARSE_REGEX


def regex_fallback_candidates(repo: str, relpath: str, source: str) -> list[Candidate]:
    """§2.1 strategy 3. Emits assign_module-tagged candidates from whole-line
    NAME = <literal> / NAME: T = <literal> matches. Same exclusion flags as the
    ast path, so net_flagged() semantics are identical."""
    out: list[Candidate] = []
    in_test = is_test_path(relpath)
    for i, line in enumerate(source.splitlines(), start=1):
        m = FRAGMENT_ASSIGN_RE.match(line)
        if not m:
            continue
        name, raw = m.group(1), m.group(2)
        if raw == "True":
            val = True
        elif raw == "False":
            val = False
        else:
            try:
                val = int(raw)
            except ValueError:
                continue
        out.append(Candidate(
            repo=repo, path=relpath, line=i, value=val, value_repr=repr(val),
            context="assign_module", target_name=name,
            is_upper=is_upper_name(name), in_range_call=False,
            in_test_path=in_test,
            in_excluded_values=(not isinstance(val, bool)) and val in EXCLUDED_VALUES,
        ))
    return out


def scan_source_fragment(repo: str, relpath: str, source: str):
    """Fragment-robust scan. Returns (candidates, strategy_used).
    Strategies 1-2 give a full ast.walk (all three contexts); strategy 3 gives
    context 3 only, per §2.1's robustness table."""
    tree, strategy = parse_fragment(source)
    if tree is None:
        cands = regex_fallback_candidates(repo, relpath, source)
        return cands, (PARSE_REGEX if cands else PARSE_REGEX)
    lines = source.splitlines()
    sc = Scanner(repo, relpath, lines, is_test_path(relpath))
    sc.mark_range_args(tree)
    sc.visit(tree)
    sc.scan_assignments(tree)
    return sc.out, strategy


